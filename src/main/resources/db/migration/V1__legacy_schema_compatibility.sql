DO $$
DECLARE
    table_rename RECORD;
BEGIN
    FOR table_rename IN
        SELECT *
        FROM (VALUES
            ('tour', 'tours'),
            ('tour_departure', 'departures'),
            ('tour_booking', 'bookings'),
            ('car', 'cars'),
            ('car_booking', 'car_bookings'),
            ('app_user', 'app_users'),
            ('tour_operator', 'tour_operators'),
            ('site_hit_counter', 'site_hit_counters'),
            ('site_page_hit', 'site_page_hits'),
            ('tour_special_experience', 'add_ons'),
            ('tour_special_experiences', 'add_ons'),
            ('booking_add_ons', 'booking_special_experiences'),
            ('booking_special_experience', 'booking_special_experiences')
        ) AS names(old_name, new_name)
    LOOP
        IF to_regclass('public.' || table_rename.old_name) IS NOT NULL THEN
            IF to_regclass('public.' || table_rename.new_name) IS NOT NULL THEN
                RAISE EXCEPTION 'Both legacy table % and target table % exist',
                    table_rename.old_name, table_rename.new_name;
            END IF;

            EXECUTE format(
                'ALTER TABLE public.%I RENAME TO %I',
                table_rename.old_name,
                table_rename.new_name
            );
        END IF;
    END LOOP;
END
$$;

