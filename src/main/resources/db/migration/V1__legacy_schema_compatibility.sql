CREATE TABLE IF NOT EXISTS site_page_hits (
    page_path VARCHAR(2048) CONSTRAINT pk_site_page_hits PRIMARY KEY,
    visit_count BIGINT NOT NULL
        CONSTRAINT ck_site_page_hits_visit_count CHECK (visit_count > 0),
    last_visited_at TIMESTAMPTZ NOT NULL
);

DO $$
BEGIN
    IF to_regclass('public.site_hit') IS NOT NULL THEN
        IF EXISTS (
            SELECT 1
            FROM information_schema.columns
            WHERE table_schema = 'public'
              AND table_name = 'site_hit'
              AND column_name = 'visited_at'
        ) THEN
            INSERT INTO site_page_hits (page_path, visit_count, last_visited_at)
            SELECT page_path, COUNT(*), MAX(visited_at)
            FROM site_hit
            GROUP BY page_path
            ON CONFLICT (page_path) DO UPDATE
            SET visit_count = site_page_hits.visit_count + EXCLUDED.visit_count,
                last_visited_at = GREATEST(
                    site_page_hits.last_visited_at,
                    EXCLUDED.last_visited_at
                );
        END IF;

        DROP TABLE public.site_hit;
    END IF;
END
$$;

