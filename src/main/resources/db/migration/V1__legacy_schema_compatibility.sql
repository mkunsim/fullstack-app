ON CONFLICT (id) DO NOTHING;

CREATE TABLE IF NOT EXISTS add_ons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY
        CONSTRAINT pk_add_ons PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    description VARCHAR(2000) NOT NULL,
    preference VARCHAR(1000) NOT NULL DEFAULT '',
    price NUMERIC(10, 2) NOT NULL
        CONSTRAINT ck_add_ons_price CHECK (price >= 0),
    available BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS booking_special_experiences (
    booking_id BIGINT NOT NULL,
    selection_order INTEGER NOT NULL,
    experience_id BIGINT NOT NULL,
    name VARCHAR(120) NOT NULL,
    description VARCHAR(2000) NOT NULL,
    preference VARCHAR(1000) NOT NULL DEFAULT '',
    price NUMERIC(10, 2) NOT NULL
        CONSTRAINT ck_booking_special_experiences_price CHECK (price >= 0),
    available BOOLEAN NOT NULL DEFAULT TRUE,
    CONSTRAINT pk_booking_special_experiences
        PRIMARY KEY (booking_id, selection_order)
);

DO $$
BEGIN
    IF to_regclass('public.add_ons') IS NOT NULL THEN
        IF EXISTS (
            SELECT 1 FROM information_schema.columns
            WHERE table_schema = 'public'
              AND table_name = 'add_ons'
              AND column_name = 'service_requirements'
        ) AND NOT EXISTS (
            SELECT 1 FROM information_schema.columns
            WHERE table_schema = 'public'
              AND table_name = 'add_ons'
              AND column_name = 'preference'
        ) THEN
            ALTER TABLE public.add_ons
                RENAME COLUMN service_requirements TO preference;
        END IF;

        IF EXISTS (
            SELECT 1 FROM information_schema.columns
            WHERE table_schema = 'public'
              AND table_name = 'add_ons'
              AND column_name = 'price_per_guest'
        ) AND NOT EXISTS (
            SELECT 1 FROM information_schema.columns
            WHERE table_schema = 'public'
              AND table_name = 'add_ons'
              AND column_name = 'price'
        ) THEN
            ALTER TABLE public.add_ons
                RENAME COLUMN price_per_guest TO price;
        END IF;

        ALTER TABLE public.add_ons
            ADD COLUMN IF NOT EXISTS preference VARCHAR(1000) NOT NULL DEFAULT '',
            ADD COLUMN IF NOT EXISTS available BOOLEAN NOT NULL DEFAULT TRUE;

        IF EXISTS (
            SELECT 1 FROM information_schema.columns
            WHERE table_schema = 'public'
              AND table_name = 'add_ons'
              AND column_name = 'tour_id'
        ) THEN
            ALTER TABLE public.add_ons
                ALTER COLUMN tour_id DROP NOT NULL;
        END IF;
    END IF;
END
$$;

