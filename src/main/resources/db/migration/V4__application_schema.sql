CREATE TABLE IF NOT EXISTS app_users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email VARCHAR(254) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    full_name VARCHAR(120) NOT NULL,
    role VARCHAR(20) NOT NULL,
    enabled BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_app_users_email UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS tours (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(140) NOT NULL,
    description VARCHAR(3000) NOT NULL,
    destination VARCHAR(180) NOT NULL,
    duration_days INTEGER NOT NULL,
    price_per_person NUMERIC(10, 2) NOT NULL,
    image_url VARCHAR(1000) NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS departures (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tour_id BIGINT NOT NULL,
    start_date DATE NOT NULL,
    capacity INTEGER NOT NULL,
    reserved_guests INTEGER NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    version BIGINT NOT NULL DEFAULT 0,
    CONSTRAINT fk_departures_tour_id
        FOREIGN KEY (tour_id) REFERENCES tours (id)
);

CREATE TABLE IF NOT EXISTS bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id BIGINT NOT NULL,
    departure_id BIGINT NOT NULL,
    guests INTEGER NOT NULL,
    total_amount NUMERIC(12, 2) NOT NULL,
    currency VARCHAR(3) NOT NULL DEFAULT 'USD',
    payment_amount_kes NUMERIC(12, 2),
    exchange_rate NUMERIC(10, 6),
    exchange_rate_source VARCHAR(64),
    payment_quote_expires_at TIMESTAMPTZ,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING',
    payment_status VARCHAR(20) NOT NULL DEFAULT 'UNPAID',
    action_token VARCHAR(64),
    action_token_expires_at TIMESTAMPTZ,
    payment_reference VARCHAR(128),
    payment_checkout_url VARCHAR(255),
    payment_currency VARCHAR(3) NOT NULL DEFAULT 'KES',
    CONSTRAINT fk_bookings_customer_id
        FOREIGN KEY (customer_id) REFERENCES app_users (id),
    CONSTRAINT fk_bookings_departure_id
        FOREIGN KEY (departure_id) REFERENCES departures (id)
);

CREATE TABLE IF NOT EXISTS cars (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    make VARCHAR(100) NOT NULL,
    model VARCHAR(100),
    license_plate VARCHAR(20),
    color VARCHAR(30),
    category VARCHAR(50),
    image_url VARCHAR(255) NOT NULL,
    description VARCHAR(500) NOT NULL,
    daily_rate_usd NUMERIC(38, 2) NOT NULL,
    guide_daily_rate_usd NUMERIC(38, 2) NOT NULL,
    passenger_capacity INTEGER NOT NULL,
    destination VARCHAR(255) NOT NULL,
    available BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE IF NOT EXISTS car_bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    car_id BIGINT,
    customer_id BIGINT,
    pickup_date DATE NOT NULL,
    dropoff_date DATE NOT NULL,
    booking_date DATE NOT NULL,
    passenger_count INTEGER NOT NULL,
    days INTEGER NOT NULL,
    pickup_location VARCHAR(255) NOT NULL,
    dropoff_location VARCHAR(255) NOT NULL,
    currency VARCHAR(255) NOT NULL,
    status VARCHAR(255) NOT NULL,
    guide_included BOOLEAN NOT NULL,
    total_amount NUMERIC(38, 2) NOT NULL,
    payment_amount_kes NUMERIC(38, 2),
    exchange_rate NUMERIC(38, 2),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_car_bookings_car_id
        FOREIGN KEY (car_id) REFERENCES cars (id),
    CONSTRAINT fk_car_bookings_customer_id
        FOREIGN KEY (customer_id) REFERENCES app_users (id)
);

CREATE TABLE IF NOT EXISTS tour_operators (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    title VARCHAR(100) NOT NULL,
    address VARCHAR(255),
    phone VARCHAR(100),
    email VARCHAR(150) NOT NULL,
    website VARCHAR(255),
    motto VARCHAR(255)
);

CREATE TABLE IF NOT EXISTS auth_sessions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    token_hash VARCHAR(64) NOT NULL,
    email VARCHAR(254) NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    revoked_at TIMESTAMPTZ
);

