    ADD COLUMN IF NOT EXISTS exchange_rate NUMERIC(10, 6),
    ADD COLUMN IF NOT EXISTS exchange_rate_source VARCHAR(64),
    ADD COLUMN IF NOT EXISTS payment_quote_expires_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS payment_currency VARCHAR(3) NOT NULL DEFAULT 'KES',
    ADD COLUMN IF NOT EXISTS action_token VARCHAR(64),
    ADD COLUMN IF NOT EXISTS action_token_expires_at TIMESTAMPTZ,
    ADD COLUMN IF NOT EXISTS payment_reference VARCHAR(128),
    ADD COLUMN IF NOT EXISTS payment_checkout_url VARCHAR(255);

CREATE UNIQUE INDEX IF NOT EXISTS uk_bookings_action_token
    ON bookings (action_token)
    WHERE action_token IS NOT NULL;
CREATE INDEX IF NOT EXISTS idx_departures_tour_id_start_date
    ON departures (tour_id, start_date);
CREATE UNIQUE INDEX IF NOT EXISTS idx_auth_sessions_token_hash
    ON auth_sessions (token_hash);
